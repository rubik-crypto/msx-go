// Package coordconv 在中国地图常见的三种坐标系（WGS-84、GCJ-02、BD-09）之间转换经纬度。
//
// 中国大陆的地图产品会在地理坐标上加一层偏移：手机 GPS 拿到的是 WGS-84，
// 腾讯、高德等地图使用 GCJ-02，百度地图又在 GCJ-02 上叠加了 BD-09 的偏移。
// 同一个地点换算前后可能相差几百米，涉及中国境内定位、地图展示或坐标入库时，
// 需要明确当前数值属于哪一套。偏移范围之外（境外）WGS-84 与 GCJ-02 相等。
//
// 示例：
//
//	p := coordconv.WGS84ToGCJ02(coordconv.Point{Lat: 39.915, Lng: 116.404})
//	// p 约为 {Lat: 39.916404, Lng: 116.410244}
